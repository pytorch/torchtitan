"""Example fusion-finder recipes: DeepSeek-V3 671B MXFP8 Dist-MoE, fake PG, one GPU.

Copy and adapt for another model: build the GraphTrainer config the way the
model's verified recipe does, then call ``enable_fusion_finder``. Run from the repo
root with this directory (and, for the lifted run, the capture directory) on PYTHONPATH:

    SKILL=torchtitan/experiments/graph_trainer/.claude/skills/fusion_region_finder/scripts
    PYTHONPATH=$SKILL:. NGPU=256 LOCAL_RANK=0 CUDA_VISIBLE_DEVICES=0 \\
        PYTORCH_ALLOC_CONF=expandable_segments:True \\
        python -m torchtitan.train --module example_recipe --config dsv3_671b_fake --comm-backend fake
"""

import os

from fusion_finder_passes import enable_fusion_finder

from torchtitan_recipes.graph_trainer.deepseek_v3 import (
    graph_trainer_deepseek_v3_671b_dist_moe_mxfp8,
)

OUT = os.path.abspath(
    os.environ.get("FUSION_FINDER_OUT", "outputs/fusion_finder/dsv3_671b")
)


def dsv3_671b_base():
    """The verified 671B MXFP8 Dist-MoE recipe (fused MLA and SwiGLU) on one fake-PG GPU.

    Only the layout changes: FSDP 256 x EP 64 without PP, and one microbatch per step
    so the profiled step is one forward and backward. With one microbatch, deferring
    gradient reduction to the last one changes nothing, and GraphTrainer without PP
    rejects the flag.
    """
    config = graph_trainer_deepseek_v3_671b_dist_moe_mxfp8()
    config.parallelism.data_parallel_shard_degree = 256
    config.parallelism.expert_parallel_degree = 64
    config.parallelism.pipeline_parallel_degree = 1
    config.parallelism.fsdp_defer_gradient_reduction = False
    config.training.num_tokens_per_train_step = -1
    # Under the fake PG every EP peer aliases this rank, so all 64 send exactly this
    # rank's routing: imbalance does not average out and can exceed the recipe's 4x
    # receive capacity (a device trap in dist_moe's routing kernel). EP x covers the
    # worst case; expert GEMM sizes then follow this rank's routing, not real traffic.
    config.dist_moe_runtime.scratch_capacity_factor = float(
        config.parallelism.expert_parallel_degree
    )
    return config


def dsv3_671b_fake():
    return enable_fusion_finder(dsv3_671b_base(), OUT)


def dsv3_671b_fake_lifted():
    """The same step with the found regions lifted into call_module nodes (loss must not change)."""
    import fusion_regions  # generated by curate_regions.py in OUT

    config = enable_fusion_finder(dsv3_671b_base(), os.path.join(OUT, "lifted"))
    # Or a hand-picked list such as ["lift_fusion_region_g003"].
    config.compile.extra_passes = list(fusion_regions.DEFAULT_SELECTION)
    return config
