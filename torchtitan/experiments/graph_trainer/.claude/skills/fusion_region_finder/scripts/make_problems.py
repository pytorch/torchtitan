def _feeds_loss_target(name):
    """``name`` reaches the target argument of nll_loss through views and splits."""
    frontier, seen = [name], {name}
    for _ in range(6):
        nxt = []
        for x in frontier:
            for u in NODES[x]["users"]:
                un = NODES[u]
                if (
                    un["target"].startswith("aten.nll_loss")
                    and len(un["args"]) > 1
                    and un["args"][1] == {"node": x}
                ):
                    return True
                if un["target"] in _LABEL_PATH_OPS and u not in seen:
                    seen.add(u)
                    nxt.append(u)
        frontier = nxt
    return False


def placeholder_role(name):
    """Role of a data input of the train step, from how the graph uses it."""
    if NODES[name]["op"] != "placeholder":
        return None
    m = tmeta(name)
    if m is None:
        return None
    users = [NODES[u] for u in NODES[name]["users"]]
    targets = {u["target"] for u in users}
    if m["dtype"] == "torch.bool":
        return "padding_mask"
    if m["dtype"] != "torch.int64":
        return None
    if any(
        u["target"] == "aten.embedding.default" and u["args"][1] == {"node": name}
        for u in users
    ):
        return "token_ids"
    if m["shape"] == [] and targets and targets <= {"aten.div.Tensor"}:
        return "loss_denominator"
    if m["shape"] == [1] and targets == {"aten.select.int"}:
        return "aux_denominators"
    if targets and targets <= {"aten.index.Tensor"}:
        return "positions"
    if _feeds_loss_target(name):
        return "labels"
    return None


def input_role(name, members):
    """Semantic role of an external input (decides how get_inputs() builds it)."""
    n, m = NODES[name], tmeta(name)
    role = placeholder_role(name)
    if role:
        return role
    ch = chain(name)
    t = [c[1] for c in ch]
    root_role = placeholder_role(ch[-1][0])
    dt = m["dtype"]
    if dt in ("torch.int64", "torch.int32", "torch.bool"):
        if dt == "torch.int32" and t[0] == "cumsum" and "wait_tensor" in t:
            return "offsets"
        if t[0] == "bitwise_not" and root_role == "padding_mask":
            return "not_padding"
        if t[0] == "select" and root_role == "aux_denominators":
            return "aux_denominator"
        if t[:2] == ["getitem", "split_with_sizes"] and root_role == "labels":
            return "labels"
        if t[:3] == ["sub", "add", "index"]:
            return "permuted_indices"
        if t[:5] == ["expand", "reshape", "floor_divide", "getitem", "sort"]:
            return "token_idx"
        if t[:3] == ["floor_divide", "getitem", "sort"]:
            return "token_idx"
        if t[:2] == ["getitem", "sort"]:
            return "sort_idx"
        if t[:2] == ["getitem", "topk"] and m["shape"][-1] == C.get("K"):
            return "topk_ids"
        if t[:2] == ["bitwise_and", "scatter_"]:
            return "masked_routing_map"
        if t[:2] == ["scatter_", "zeros_like"]:
            return "routing_map"
        if t[:3] == ["unsqueeze", "scatter_", "ones_like"]:
            return "unselected_groups"
        if t[:5] == ["reshape", "clone", "t", "reshape", "reshape"]:
            return "segment_lens"
        if t[:5] == ["reshape", "clone", "t", "reshape", "sub"]:
            return "input_starts_t"
        if t[:5] == ["sub", "cumsum", "reshape", "clone", "t"]:
            return "output_starts"
        if t[:3] == ["wait_tensor", "wait_tensor", "all_to_all_single"]:
            return "global_counts"
        if t[:3] == ["sum", "scatter_", "zeros_like"]:
            return "expert_counts"
        if t[:4] == ["cumsum", "sum", "scatter_", "zeros_like"]:
            return "expert_offsets"
        raise ConversionError(
            f"no role for int/bool input {name}: {' <- '.join(t[:6])}"
        )
    if dt.startswith("torch.complex"):
        return "complex_unit"
    if (
        n["target"] == "_operator.getitem"
        and NODES[n["args"][0]["node"]]["target"] == "aten._fused_rms_norm.default"
        and n["args"][1] == 1
    ):
        return "rstd"
    if n["op"] == "placeholder" and len(m["shape"]) == 1:
        for mem in members:
            mn = NODES[mem]
            if mn["target"].startswith("aten._fused_rms_norm") and name in list(
                node_refs(mn["args"])
            ):
                return "norm_weight"
    if "sigmoid" in [c[1] for c in chain(name, depth=14)]:
        return "positive_unit"
    return "randn"


