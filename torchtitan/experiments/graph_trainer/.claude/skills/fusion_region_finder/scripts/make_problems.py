def _constants(setup):
    """Sizes the generated inputs need, from setup.json; absent ones stay unset."""
    model = setup.get("model") or {}
    par = setup.get("parallelism", {})
    T = setup["num_tokens_per_microbatch_per_dp_rank"]
    c = dict(T=T, SEQ=model.get("max_context_length"), V=model.get("vocab_size"))
    if setup.get("world_size"):
        non_dp = math.prod(
            max(par.get(k, 1), 1)
            for k in (
                "tensor_parallel_degree",
                "context_parallel_degree",
                "pipeline_parallel_degree",
            )
        )
        c["DP"] = setup["world_size"] // non_dp
    router = model.get("router")
    if router:
        E, K = router["num_experts"], router["top_k"]
        EP = max(par.get("expert_parallel_degree", 1), 1)
        # Routed rows per MoE layer on this rank: T * K. Exact for local dispatch and for
        # all-to-all dispatch under the fake process group, where every rank gets T * K.
        c.update(
            E=E,
            K=K,
            G=router.get("num_expert_groups") or 1,
            L=router.get("num_limited_groups") or 1,
            EP=EP,
            LOCAL_E=E // EP,
            R=T * K,
        )
    return {k: v for k, v in c.items() if v is not None}


def node_refs(a):
    return iter_arg_nodes(a)


def resolve(x):
    """Concrete int for a symbolic dim (string expression or {'repr': expr})."""
    if isinstance(x, dict) and "repr" in x:
        x = x["repr"]
    if isinstance(x, int):
        return x
    if isinstance(x, str):
        if x in SYMS:
            return int(SYMS[x])
        if re.fullmatch(r"-?\d+", x):
            return int(x)
    raise ConversionError(f"unresolved symbol {str(x)[:60]}")


def sym_value(name):
    """Concrete value of a symbolic-int node.

    Dump reprs of long sums are truncated, so resolve structurally: sizes and numels from
    the tensor shapes, and a sum of the EP per-rank all-to-all split sizes is R.
    """
    n = NODES[name]
    v = n["val"]
    if isinstance(v, dict) and isinstance(v.get("repr"), str) and v["repr"] in SYMS:
        return int(SYMS[v["repr"]])
    t = n["target"]
    if t == "aten.sym_size.int":
        return tmeta(n["args"][0]["node"])["shape"][n["args"][1]]
    if t == "aten.sym_numel.default":
        return math.prod(tmeta(n["args"][0]["node"])["shape"])
    if t == "_operator.add" and "R" in C:
        leaves, const = [], 0
        stack = [n]
        while stack:
            x = stack.pop()
            if x["target"] == "_operator.add":
                for a in x["args"]:
                    if isinstance(a, dict) and "node" in a:
                        stack.append(NODES[a["node"]])
                    else:
                        const += a
            else:
                leaves.append(x)
        if (
            len(leaves) == C["EP"]
            and const == 0
            and all(x["target"] == "aten._local_scalar_dense.default" for x in leaves)
        ):
            return C["R"]
    raise ConversionError(f"cannot resolve symbolic node {name} ({t})")


def tmeta(name):
    v = NODES[name]["val"]
    if not (isinstance(v, dict) and v.get("t") == "tensor"):
        return None
    return dict(
        shape=[resolve(s) for s in v["shape"]],
        stride=[resolve(s) for s in v["stride"]],
        dtype=v["dtype"],
    )


def is_sym_node(name):
    n = NODES[name]
    v = n["val"]
    return n["target"] in SYM_TARGETS or (
        isinstance(v, dict)
        and "repr" in v
        and v.get("t") != "tensor"
        and re.search(r"\bu\d+", v["repr"] or "")
    )


def chain(name, depth=8):
    """(name, op, node) along first-argument producers, starting at ``name``."""
    out, cur = [], name
    for _ in range(depth):
        n = NODES[cur]
        parts = n["target"].split(".")
        out.append((cur, parts[1] if len(parts) >= 2 else parts[0], n))
        refs = list(node_refs(n["args"]))
        if n["op"] == "placeholder" or not refs:
            break
        cur = refs[0]
    return out


