def render(a, names, key=None):
    """Python source for one FX argument."""
    if isinstance(a, dict):
        if set(a) == {"node"}:
            ref = a["node"]
            if ref in names:
                return names[ref]
            if is_sym_node(ref):
                return str(sym_value(ref))
            raise ConversionError(f"unbound node {ref}")
        if set(a) == {"repr"}:
            r = a["repr"]
            if r.startswith("torch."):
                return r
            return str(resolve(r))
        return (
            "{" + ", ".join(f"{k!r}: {render(v, names, k)}" for k, v in a.items()) + "}"
        )
    if isinstance(a, list):
        return "[" + ", ".join(render(v, names, key) for v in a) + "]"
    if isinstance(a, str):
        if a.startswith("torch."):
            return a
        if key == "device" or a.startswith("cuda"):
            return "'cuda'" if a.startswith("cuda") else repr(a)
        return repr(a)
    if isinstance(a, float):
        if math.isinf(a):
            return "float('inf')" if a > 0 else "float('-inf')"
        if math.isnan(a):
            return "float('nan')"
        return repr(a)
    return repr(a)


def op_flops(n):
    """Approximate FLOPs of one node (GEMMs exact; glue ~ elementwise op count)."""
    t = n["target"]
    out = n["val"]

    def numel(v):
        if isinstance(v, dict) and v.get("t") == "tensor":
            return math.prod(resolve(s) for s in v["shape"])
        return 0

    ins = [
        tmeta(r)
        for r in node_refs(n["args"])
        if isinstance(NODES[r]["val"], dict) and NODES[r]["val"].get("t") == "tensor"
    ]
    if t in ("aten.mm.default", "aten.mm.dtype"):
        a, b = ins[0]["shape"], ins[1]["shape"]
        return 2 * a[0] * a[1] * b[1]
    if t == "aten._grouped_mm.default":
        a, b = ins[0]["shape"], ins[1]["shape"]
        if len(b) == 3:
            return 2 * math.prod(a) * b[-1]
        return 2 * a[0] * a[1] * b[-1]
    o = (
        numel(out)
        if isinstance(out, dict)
        else sum(numel(v) for v in (out or []) if isinstance(v, dict))
    )
    i0 = math.prod(ins[0]["shape"]) if ins else 0
    weights = {
        "sigmoid": 4,
        "silu": 4,
        "silu_backward": 6,
        "sigmoid_backward": 3,
        "_log_softmax": 4,
        "_log_softmax_backward_data": 3,
        "linalg_vector_norm": 2,
    }
    base = t.replace("aten.", "").split(".")[0]
    if base == "_fused_rms_norm":
        return 4 * i0
    if base == "_fused_rms_norm_backward":
        return 8 * i0
    if base in (
        "sum",
        "cumsum",
        "linalg_vector_norm",
        "nll_loss_forward",
        "embedding_dense_backward",
        "scatter_add",
        "index_put",
        "index_put_",
    ):
        return max(i0, o) * weights.get(base, 1)
    if base in ("topk", "sort"):
        width = ins[0]["shape"][-1] if ins and ins[0]["shape"] else 1
        return i0 * max(1, int(math.log2(max(width, 2))))
    if t == "torchtitan.deterministic_scatter_add.default":
        return math.prod(ins[2]["shape"])
    if base in (
        "mul",
        "add",
        "add_",
        "sub",
        "div",
        "neg",
        "where",
        "masked_fill",
        "gt",
        "bitwise_and",
        "bitwise_not",
        "clamp_min",
        "reciprocal",
        "sgn",
        "__lshift__",
        "floor_divide",
        "silu",
        "silu_backward",
        "sigmoid",
        "sigmoid_backward",
        "_log_softmax",
        "_log_softmax_backward_data",
        "nll_loss_backward",
        "_conj",
    ):
        complex_mul = base == "mul" and any(
            m.get("dtype", "").startswith("torch.complex") for m in ins if m
        )
        return o * weights.get(base, 1) * (6 if complex_mul else 1)
    return 0


