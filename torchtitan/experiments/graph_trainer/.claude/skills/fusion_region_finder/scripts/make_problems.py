def write_problem(pdir, c, *, model_tag, same, key, setup, cal, device):
    r = c["region"]
    folder = os.path.basename(pdir)
    source = build_source(c, model_tag, same)
    ast.parse(source)

    def read_by_region(spec):
        users = [
            m
            for m in c["members"]
            if spec["node"]
            in list(node_refs(NODES[m]["args"])) + list(node_refs(NODES[m]["kwargs"]))
        ]
        return any(NODES[u]["target"] not in SHAPE_ONLY_TARGETS for u in users)

    in_bytes = sum(
        nbytes(s["shape"], s["stride"], s["dtype"])
        for s in c["specs"]
        if read_by_region(s)
    )
    out_bytes = sum(nbytes(e["shape"], e["stride"], e["dtype"]) for e in c["expected"])
    num_bytes = in_bytes + out_bytes
    flops = max(int(sum(op_flops(NODES[m]) for m in c["members"])), 1)
    t_compute = flops / (cal["bf16_gemm_tflops"] * 1e12)
    t_mem = num_bytes / (cal["hbm_gbps"] * 1e9)
    if not c["targets"] & GEMM_OPS:
        bound = "memory"
    elif t_compute > 1.5 * t_mem:
        bound = "compute"
    elif t_compute < t_mem / 1.5:
        bound = "memory"
    else:
        bound = "mixed"
    tier = r["bitwise_tier"]
    phase_tag = "+".join(p[:3] for p in r["phases"])
    op_type = folder.split("_", 1)[1]
    biggest = max(c["specs"], key=lambda s: nbytes(s["shape"], s["stride"], s["dtype"]))
    if any(s["dtype"] == "torch.bfloat16" for s in c["specs"]):
        dtype = "bf16"
    else:
        dtype = PAYLOAD_DTYPE[biggest["dtype"]]
    big = sorted(
        c["specs"], key=lambda s: -nbytes(s["shape"], s["stride"], s["dtype"])
    )[:3]
    dims = "_".join(
        f"{DTYPE_SHORT[s['dtype']]}{'x'.join(map(str, s['shape']))}" for s in big
    )
    shape = f"{model_tag}_{r['id'].replace('-', '')}_{phase_tag}_{dims}"[:255]
    par = ", ".join(
        f"{short} {setup['parallelism'][k]}"
        for k, short in PARALLELISM_SHORT.items()
        if setup.get("parallelism", {}).get(k, 1) not in (1, -1)
    )
    run = f"world size {setup.get('world_size', '?')}" + (f", {par}" if par else "")
    src = (
        r["location"].get("source", "").replace("torchtitan/torchtitan/", "torchtitan/")
    )
    desc = [
        f"{model_tag} training-step fusion region {r['id']} found by the fusion region finder "
        f"(GraphTrainer joint fwd+bwd FX graph; {run}; {C['T']:,} tokens/microbatch"
        f"{'; ' + device if device else ''}).",
        f"Region: {r['title']}.",
        f"Same computation as regions: {', '.join(same)}.",
        f"Phases: {', '.join(r['phases'])}; scope: {', '.join(r['scope'])}; "
        f"fusion kind: {r['fusion_kind']}; source: {src}.",
        f"Profiled: {r['instances_per_step']} instances/step, "
        f"{r['kernels_per_instance']:.0f} kernels/instance, "
        f"{r['measured_us_per_instance']:.0f} us measured vs {r['ideal_us_per_instance']:.0f} us "
        f"ideal per instance (gap {r['gap_ms_total']:.1f} ms/step, "
        f"{r['gap_pct_of_step']:.2f}% of step).",
        "Reference: replays the region's exact aten ops from the traced graph in graph order; "
        "ops that the training run executed under torch.use_deterministic_algorithms(True) "
        "run in deterministic mode here.",
        f"Bitwise tier {tier}: {r['bitwise_notes']}",
    ]
    if c["targets"] & {
        "torchtitan.deterministic_scatter_add.default",
        "aten.index_put.default",
        "aten.index_put_.default",
        "aten.scatter_add.default",
    }:
        desc.append(
            "Accumulation rule: aten's deterministic index_put/scatter_add at row width > 32 "
            "(indexing_backward_kernel) adds duplicates in stable-sorted original-position "
            "order and rounds to the destination dtype after every add (load, fp32 add, "
            "store); a fused kernel must do the same."
        )
    desc.append(
        "num_flops: GEMMs 2*M*N*K exactly; other ops approximated as elementwise op counts "
        "(about 1 per output element, sigmoid/silu ~4, RMSNorm ~4 per input element, sorts "
        f"~log2(width)). num_bytes: one read of each input ({in_bytes} B) and one write of "
        f"each output ({out_bytes} B); broadcast (stride-0) tensors counted once; inputs "
        "used only for their shape (zeros_like, new_zeros, ...) not counted."
    )
    desc.append(
        "Inputs: "
        + "; ".join(
            f"{s['var']} {DTYPE_SHORT[s['dtype']]}{s['shape']}"
            f"{' stride' + str(s['stride']) if s['stride'] != _contig(s['shape']) else ''}"
            f" = {ROLE_DOC[s['role']]}"
            for s in c["specs"]
        )
        + "."
    )
    if c["mutated"]:
        desc.append(
            "Inputs updated in place by the region are cloned first and returned as outputs."
        )
    if "ag" in c["used"]:
        desc.append(
            "The FSDP all-gather pack is reduced to the bytes it writes on rank 0 (the rest "
            "of its buffer is uninitialized collective space)."
        )
    desc.append(
        "Tolerance: default (contains a GEMM; bitwise identity would require cuBLAS's exact "
        "algorithm)."
        if tier == "T3"
        else "Tolerance: max_valid_ulp=0 and max_valid_abs_diff=0 (bitwise identity)."
    )
    payload = {
        "op_type": op_type,
        "shape": shape,
        "dtype": dtype,
        "bound_type": bound,
        "usage": "training",
        "num_gpus": 1,
        "num_kernels": 1,
        "num_flops": flops,
        "num_bytes": int(num_bytes),
        "arithmetic_intensity": round(flops / num_bytes, 6),
        "reference_src": source,
        "description": " ".join(desc)[:10000],
    }
    if tier != "T3":
        payload["max_valid_ulp"] = 0
        payload["max_valid_abs_diff"] = 0
    for k in ("num_flops", "num_bytes", "num_gpus", "num_kernels"):
        assert type(payload[k]) is int and 0 < payload[k] <= 2**53 - 1, (
            folder,
            k,
            payload[k],
        )
    assert len(payload["reference_src"]) <= 2_000_000 and len(payload["shape"]) <= 255
    with open(os.path.join(pdir, "problem.py"), "w") as f:
        f.write(source)
    with open(os.path.join(pdir, "payload.json"), "w") as f:
        f.write(
            json.dumps(payload, ensure_ascii=True, allow_nan=False, indent=2) + "\n"
        )
    var_names = [line.split("=")[0].strip() for line in c["body"] if "=" in line]
    meta = dict(
        region=r["id"],
        same_computation_as=[x for x in same if x != r["id"]],
        tier=tier,
        bound=bound,
        gap_ms_total=r["gap_ms_total"],
        candidate=c["cand"]["cand_id"],
        example_instance_members=dict(zip(var_names, c["members"])),
        inputs=[
            {k: s[k] for k in ("var", "node", "role", "shape", "stride", "dtype")}
            for s in c["specs"]
        ],
        expected_outputs=c["expected"],
        in_bytes=in_bytes,
        out_bytes=out_bytes,
        num_flops=flops,
        finder_bytes_per_instance=r["external_bytes_per_instance"],
        key=key,
    )
    with open(os.path.join(pdir, "problem_meta.json"), "w") as f:
        f.write(json.dumps(meta, indent=1) + "\n")


def main():
    global NODES, SYMS, C
    ap = argparse.ArgumentParser()
    ap.add_argument("root", help="capture directory (after curate_regions.py)")
    ap.add_argument(
        "--model-tag",
        required=True,
        help="model name used in problem names and descriptions, e.g. dsv3_671b",
    )
    args = ap.parse_args()
    R = args.root
    with gzip.open(os.path.join(R, "graph_dump", "final_nodes.jsonl.gz"), "rt") as f:
        NODES = {n["name"]: n for n in map(json.loads, f)}
    SYMS = json.load(open(os.path.join(R, "analysis", "symbols.json")))["symbols"]
    cands = {
        c["cand_id"]: c
        for c in json.load(open(os.path.join(R, "analysis", "candidates.json")))
    }
    setup = json.load(open(os.path.join(R, "setup.json")))
    roof = json.load(open(os.path.join(R, "roofline.json")))
    C = _constants(setup)
    folders = sorted(glob.glob(os.path.join(R, "fusion_regions", "*", "region.json")))
    if not folders:
        raise ValueError(
            f"no fusion_regions/*/region.json in {R}; run curate_regions.py first"
        )

    converted, failed = [], []
    for path in folders:
        pdir = os.path.dirname(path)
        # A previous validation.json describes the old problem.
        for name in (
            "problem.py",
            "payload.json",
            "problem_meta.json",
            "validation.json",
        ):
            if os.path.exists(os.path.join(pdir, name)):
                os.remove(os.path.join(pdir, name))
        r = json.load(open(path))
        try:
            converted.append((pdir, convert_region(r, cands)))
        except ConversionError as e:
            failed.append((pdir, r["id"], str(e)))
    groups = collections.defaultdict(list)
    for pdir, c in converted:
        groups[code_key(c)].append(c["region"]["id"])
    for pdir, c in converted:
        key = code_key(c)
        write_problem(
            pdir,
            c,
            model_tag=args.model_tag,
            same=sorted(groups[key]),
            key=key,
            setup=setup,
            cal=roof["roofline"],
            device=roof.get("device", ""),
        )
    for pdir, rid, err in failed:
        with open(os.path.join(pdir, "problem_meta.json"), "w") as f:
            f.write(json.dumps(dict(region=rid, error=err), indent=1) + "\n")
    print(
        f"regions {len(folders)}; problems {len(converted)} "
        f"({len(groups)} distinct computations); not converted {len(failed)}"
    )
    for _, rid, err in failed:
        print(f"  {rid}: {err}")


