HELPER_CONTEXT = '''
def _routing_context():
    """One consistent routing sample: group-limited top-K, dispatch sort, EP counts."""
    scores = torch.rand(T, E, device=DEV)
    grouped = scores.view(T, G, E // G)
    group_scores = grouped.topk(min(2, E // G), dim=-1).values.sum(dim=-1)
    selected_groups = group_scores.topk(L, dim=-1, sorted=False).indices
    unselected = torch.ones(T, G, dtype=torch.bool, device=DEV).scatter_(-1, selected_groups, False)
    masked = grouped.masked_fill(unselected.unsqueeze(-1), float("-inf")).flatten(-2)
    topk_ids = masked.topk(K, dim=-1, sorted=False).indices
    routing_map = torch.zeros(T, E, dtype=torch.bool, device=DEV).scatter_(-1, topk_ids, True)
    sort_idx = torch.argsort(topk_ids.view(-1), stable=True)
    # Routed rows per (source EP rank, local expert): balanced multinomial summing exactly to R.
    t_mat = torch.multinomial(torch.ones(EP * LOCAL_E, device=DEV), R, replacement=True)
    t_mat = t_mat.bincount(minlength=EP * LOCAL_E).view(EP, LOCAL_E)
    counts = t_mat.reshape(-1)
    input_starts = (counts.cumsum(0) - counts).view(EP, LOCAL_E)
    segment_lens = t_mat.t().reshape(-1)
    input_starts_t = input_starts.t().reshape(-1)
    seg_ids = torch.arange(segment_lens.numel(), device=DEV).repeat_interleave(segment_lens, output_size=R)
    output_starts = segment_lens.cumsum(0) - segment_lens
    permuted = input_starts_t[seg_ids] + torch.arange(R, device=DEV) - output_starts[seg_ids]
    return {
        "topk_ids": topk_ids, "routing_map": routing_map, "unselected_groups": unselected.unsqueeze(-1),
        "sort_idx": sort_idx, "token_idx": sort_idx // K, "global_counts": counts,
        "offsets": t_mat.sum(0).cumsum(0).to(torch.int32), "segment_lens": segment_lens,
        "input_starts_t": input_starts_t, "output_starts": output_starts, "permuted_indices": permuted,
        "expert_counts": routing_map.sum(0), "expert_offsets": routing_map.sum(0).cumsum(0),
    }
'''

