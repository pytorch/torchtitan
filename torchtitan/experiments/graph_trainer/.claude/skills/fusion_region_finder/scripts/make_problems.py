def view_root(o, ms):
    """Follow view ops inside the region back to the tensor whose storage they alias.

    Returns (root, full): full is False if any step selects part of the storage.
    """
    full = True
    while o in ms:
        n = NODES[o]
        t = n["target"]
        a0 = n["args"][0] if n["args"] else None
        src = a0["node"] if isinstance(a0, dict) and "node" in a0 else None
        if t in FULL_VIEW_TARGETS:
            o = src
        elif (
            t == "aten.slice.Tensor"
            and NODES[src]["target"] == AG_TARGET
            and n["args"][2] == 0
            and n["args"][3] == ag_local_numel(src)
        ):
            o = src  # the local slice of the all-gather pack is the whole local output
        elif t in PARTIAL_VIEW_TARGETS:
            o, full = src, False
        elif t == "_operator.getitem" and NODES[src]["target"] in SPLIT_TARGETS:
            o, full = NODES[src]["args"][0]["node"], False
        else:
            break
    return o, full


def ag_local_numel(name):
    """Elements of the all-gather pack this rank writes (the buffer has group_size slices)."""
    return (
        math.prod(resolve(x) for x in NODES[name]["val"]["shape"])
        // NODES[name]["args"][1]
    )


def region_members(r, cands):
    """The finder candidate a region came from and its example instance's nodes."""
    c = cands[int(re.search(r"candidate #(\d+)", r["how_found"]).group(1))]
    return c, list(c["example_members"])


def boundary(members):
    """External inputs (graph order of first use) and members used outside the region."""
    ms = set(members)
    ins, seen = [], set()
    ordered = sorted(members, key=lambda x: NODES[x]["idx"])
    for m in ordered:
        n = NODES[m]
        for ref in list(node_refs(n["args"])) + list(node_refs(n["kwargs"])):
            if ref not in ms and ref not in seen:
                seen.add(ref)
                ins.append(ref)
    outs = [
        m
        for m in ordered
        if any(u not in ms for u in NODES[m]["users"]) or NODES[m]["users"] == []
    ]
    return ins, outs


def _is_inplace(t):
    return t.startswith("aten.") and (
        t.endswith("_.Tensor") or t.endswith("_.default") or t.endswith("_.value")
    )


def convert_region(r, cands):
    cand, members = region_members(r, cands)
    # Promote getitem members whose tuple source is external (e.g. attention backward outputs).
    ms = set(members)
    members = [
        m
        for m in members
        if not (
            NODES[m]["target"] == "_operator.getitem"
            and NODES[m]["args"][0]["node"] not in ms
        )
    ]
    ms = set(members)
    ins, outs = boundary(members)
    ins = [i for i in ins if not is_sym_node(i)]
    members = sorted(members, key=lambda x: NODES[x]["idx"])
    for i in ins:
        if tmeta(i) is None:
            raise ConversionError(
                f"non-tensor external input {i} ({NODES[i]['target']})"
            )
    names, lines, mutated, written_by_out = {}, [], [], []
    for k, i in enumerate(ins):
        names[i] = f"in{k}"
    used, targets = set(), set()
    for k, m in enumerate(members):
        n = NODES[m]
        t = n["target"]
        targets.add(t)
        args = [render(a, names) for a in n["args"]]
        kwargs = [f"{key}={render(v, names, key)}" for key, v in n["kwargs"].items()]
        var = f"t{k}"
        deterministic = False
        if t == "_operator.getitem":
            expr = f"{args[0]}[{args[1]}]"
        elif t in SYM_TARGETS:
            if t == "aten.sym_size.int":
                expr = f"{args[0]}.size({args[1]})"
            elif t == "aten.sym_numel.default":
                expr = f"{args[0]}.numel()"
            else:
                op = {
                    "_operator.add": "+",
                    "_operator.mul": "*",
                    "_operator.sub": "-",
                    "_operator.floordiv": "//",
                }[t]
                expr = f"({args[0]} {op} {args[1]})"
        elif t == "torchtitan.deterministic_scatter_add.default":
            used.update({"det", "dsa"})
            expr = f"_deterministic_scatter_add({', '.join(args)})"
        elif t == "bucketing._pre_bucket_reduce_scatter.default":
            used.add("rs")
            expr = f"_pre_bucket_reduce_scatter({', '.join(args + kwargs)})"
        elif t == AG_TARGET:
            used.add("ag")
            out_dtypes = [str(_ALL_DTYPES[d]) for d in n["args"][3]]
            expr = f"_pre_bucket_all_gather_local({args[0]}, {args[2]}, [{', '.join(out_dtypes)}])"
        elif t.startswith("aten."):
            _, op, overload = t.split(".")
            expr = f"torch.ops.aten.{op}.{overload}({', '.join(args + kwargs)})"
            deterministic = t in DETERMINISTIC_OPS
        else:
            raise ConversionError(f"unsupported target {t}")
        if _is_inplace(t):
            first = view_root(n["args"][0]["node"], ms)[0]
            if first in ins:
                mutated.append(names[first])
        if t.endswith(".out"):
            # The out= tensors are the results: return them, and clone the inputs they view.
            for x in node_refs(n["kwargs"].get("out", [])):
                root = view_root(x, ms)[0]
                if root in ins:
                    mutated.append(names[root])
                if x not in written_by_out:
                    written_by_out.append(x)
        if deterministic:
            used.add("det")
            lines.append("        with _deterministic():")
            lines.append(f"            {var} = {expr}  # {m}")
        else:
            lines.append(f"        {var} = {expr}  # {m}")
        names[m] = var
    # Outputs. A view chain that ends at an input is a pass-through: drop it. Full-storage
    # aliases of the same member (alias, view, transpose, ...) are one output: keep the
    # root, else the first.
    kept, seen = [], {}
    for o in outs:
        root, full = view_root(o, ms)
        if root not in ms:
            continue
        if not full:
            kept.append(o)
        elif root in seen:
            if o == root:
                kept[kept.index(seen[root])] = o
                seen[root] = o
        else:
            seen[root] = o
            kept.append(o)
    ret, expected = [], []
    for o in kept:
        v = NODES[o]["val"]
        if isinstance(v, list):
            for j, x in enumerate(v):
                if isinstance(x, dict) and x.get("t") == "tensor":
                    ret.append(f"{names[o]}[{j}]")
                    expected.append(
                        dict(
                            shape=[resolve(s) for s in x["shape"]],
                            stride=[resolve(s) for s in x["stride"]],
                            dtype=x["dtype"],
                        )
                    )
        elif NODES[o]["target"] == AG_TARGET:
            ret.append(names[o])
            expected.append(
                dict(shape=[ag_local_numel(o)], stride=[1], dtype=v["dtype"])
            )
        elif isinstance(v, dict) and v.get("t") == "tensor":
            ret.append(names[o])
            expected.append(
                dict(
                    shape=[resolve(s) for s in v["shape"]],
                    stride=[resolve(s) for s in v["stride"]],
                    dtype=v["dtype"],
                )
            )
    for x in written_by_out:
        ret.append(names[x])
        expected.append(tmeta(x))
    if not ret:
        raise ConversionError("region has no tensor outputs")
    specs = []
    for i in ins:
        role = input_role(i, members)
        missing = [k for k in ROLE_NEEDS.get(role, []) if k not in C]
        if missing:
            raise ConversionError(
                f"input {i} ({role}) needs {missing}, which setup.json lacks"
            )
        specs.append(dict(node=i, var=names[i], role=role, **tmeta(i)))
    return dict(
        region=r,
        cand=cand,
        members=members,
        specs=specs,
        body=lines,
        ret=ret,
        expected=expected,
        mutated=sorted(set(mutated)),
        used=used,
        targets=targets,
    )


def build_source(c, model_tag, same):
    r = c["region"]
    specs = c["specs"]
    need_ctx = any(s["role"] in CTX_ROLES for s in specs)
    used = set(c["used"])
    src = (
        r["location"].get("source", "").replace("torchtitan/torchtitan/", "torchtitan/")
    )
    doc = [
        f'"""KernelGen reference: {model_tag} fusion region {r["id"]}.',
        "",
        f"{r['title']}",
        "",
        f"Regions with this exact computation: {', '.join(same)}.",
        f"Phases: {', '.join(r['phases'])}; scope: {', '.join(r['scope'])}; source: {src}.",
        "The forward replays the region's aten ops exactly as GraphTrainer's traced train step",
        "runs them (node names in comments), so a candidate kernel must reproduce these outputs",
        "bit for bit. Generated by fusion_region_finder/scripts/make_problems.py.",
        '"""',
    ]
    head = doc + [
        "import contextlib",
        "",
        "import torch",
        "import torch.nn as nn",
        "",
        'DEV = "cuda"',
    ]
    keys = [k for k in ["T", "SEQ", "V", "DP"] if k in C]
    head.append(", ".join(keys) + " = " + ", ".join(str(C[k]) for k in keys))
    if need_ctx:
        head.append(", ".join(ROUTING) + " = " + ", ".join(str(C[k]) for k in ROUTING))
    helpers = []
    if "det" in used:
        helpers.append(HELPER_DET)
    if "dsa" in used:
        helpers.append(HELPER_DSA)
    if "rs" in used:
        helpers.append(HELPER_RS)
    if "ag" in used:
        helpers.append(HELPER_AG)
    helpers.append(HELPER_LAYOUT)
    if need_ctx:
        helpers.append(HELPER_CONTEXT)
    sig = ", ".join(s["var"] for s in specs)
    body = ["", "", "class Model(nn.Module):", f"    def forward(self, {sig}):"]
    for v in c["mutated"]:
        body.append(
            f"        {v} = {v}.clone()  # mutated in place by the region; keep the caller's tensor"
        )
    body += c["body"]
    ret = c["ret"]
    body.append(
        f"        return {ret[0]}"
        if len(ret) == 1
        else f"        return ({', '.join(ret)},)"
    )
    body += [
        "",
        "",
        "def get_init_inputs():",
        "    return []",
        "",
        "",
        "def get_inputs():",
    ]
    if need_ctx:
        body.append("    ctx = _routing_context()")
    body.append("    return [")
    for s in specs:
        comma = "," if len(s["shape"]) == 1 else ""
        gshape = (
            "("
            + ", ".join(
                str(1 if st == 0 else x) for x, st in zip(s["shape"], s["stride"])
            )
            + comma
            + ")"
        )
        expr = ROLE_EXPR[s["role"]].format(shape=gshape)
        body.append(f"        # {s['var']} <- {s['node']}: {ROLE_DOC[s['role']]}")
        body.append(
            f"        _layout({expr}, {list(s['shape'])}, {list(s['stride'])}, {s['dtype']}),"
        )
    body.append("    ]")
    return "\n".join(head) + "\n" + "\n".join(helpers) + "\n".join(body) + "\n"


def code_key(c):
    """Hash of the computation (code without comments + input specs) for de-duplication."""
    body = [re.sub(r"\s+#.*$", "", line) for line in c["body"]]
    spec = [(s["role"], s["shape"], s["stride"], s["dtype"]) for s in c["specs"]]
    return hashlib.sha256(
        json.dumps([body, spec, c["ret"], c["mutated"]]).encode()
    ).hexdigest()[:16]


def nbytes(shape, stride, dtype):
    return (
        math.prod(1 if st == 0 else s for s, st in zip(shape, stride)) * ITEMSIZE[dtype]
    )


def _contig(shape):
    st, acc = [], 1
    for s in reversed(shape):
        st.append(acc)
        acc *= s
    return list(reversed(st))


